import 'package:flutter/material.dart';

String tr(BuildContext context, String value) {
  final code = Localizations.localeOf(context).languageCode;
  return translateValue(code, value);
}

String translateValue(String code, String value) {
  final words = translations[code] ?? translations['en']!;

  final exact = words[value.toLowerCase()];
  if (exact != null) return exact;

  if (value.contains('\n')) {
    return value.split('\n').map((v) => translateValue(code, v)).join('\n');
  }

  if (value.contains(' • ')) {
    return value.split(' • ').map((v) => translateValue(code, v)).join(' • ');
  }

  final colon = value.indexOf(': ');
  if (colon >= 0) {
    return '${translateValue(code, value.substring(0, colon))}: '
        '${translateValue(code, value.substring(colon + 2))}';
  }

  if (value.contains(' reduced by ')) {
    final parts = value.split(' reduced by ');
    return '${translateValue(code, parts.first)} '
        '${translateValue(code, 'reduced by')} ${parts.last}';
  }

  for (final suffix in [' Analysis', ' savings', ' Acres', ' Hectares']) {
    if (value.endsWith(suffix)) {
      return '${translateValue(code, value.substring(0, value.length - suffix.length))} ${translateValue(code, suffix.trim())}';
    }
  }

  return value;
}

